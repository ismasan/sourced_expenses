# The model, faked: no spec reaches OpenAI, even with OPENAI_API_KEY in .env.
# Answers are set per schema; anything else raises. Categories are
# +category+ (a Hash, or an LLM::Error to raise), asked about in
# +categorized+.
class FakeLLM
  attr_reader :calls, :categorized, :choices
  attr_accessor :answers, :category

  def initialize = reset!

  def reset!
    @calls = []
    @answers = {}
    @categorized = []
    @category = { category: 'general', probability: 0.5 }
  end

  # +categories+, the choices it was given, are in +choices+.
  def categorize(categories:, **expense)
    @choices = categories
    @categorized << expense
    raise category if category.is_a?(Exception)

    category
  end

  def ask(instructions:, schema:, message:, file: nil)
    @calls << { instructions:, schema:, message:, file: }
    answer = answers.fetch(schema) { raise "FakeLLM has no answer for #{schema[:required].inspect}" }
    raise answer if answer.is_a?(Exception)

    answer
  end
end
FAKE_LLM = FakeLLM.new
Sidereal.config.config!('llm') { FAKE_LLM }

# Exchange rates without the network: +rates+ maps a currency to the rate
# (or the ExchangeRates::Error) every date gets.
class FakeExchangeRates
  attr_reader :calls
  attr_accessor :rates

  def initialize = reset!

  def reset!
    @calls = []
    @rates = {}
  end

  def rate(from:, to:, on:)
    @calls << { from:, to:, on: }
    rate = rates.fetch(from) { raise ExchangeRates::Error, "No exchange rate from #{from} to #{to}" }
    raise rate if rate.is_a?(Exception)

    ExchangeRates::Rate.new(rate:, date: on)
  end
end
FAKE_RATES = FakeExchangeRates.new
Sidereal.config.config!('exchange_rates') { FAKE_RATES }
