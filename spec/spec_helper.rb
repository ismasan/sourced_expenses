module MachineHelpers
  # The state event +machine+ appends moving to +to+ (a path), as a
  # decision would build it: the target's own class, a part's included.
  def moved(machine, trigger, from:, to:, exited: [], entered: [to], **keys)
    machine.tree.node_at(to).key.new(payload: { **keys, trigger:, source: from, target: to, exited:, entered: })
  end

  # +given+ plus the events +machine+ appends deciding +commands+ one after
  # another: a history to give a spec.
  def decided(machine, keys, *commands, given: [])
    commands.reduce(given) do |history, command|
      instance = machine.new(keys)
      instance.evolve(history)
      raise ArgumentError, "#{machine} doesn't take #{command.class} here" unless instance.handles_command?(command)

      read = Sourced::ReadResult.new(messages: history, guard: Sourced::ConsistencyGuard.new(selector: Sourced::Selector::NONE, last_position: 0))
      appended = machine.handle_batch(keys, [command], history: read, replaying: false).flat_map do |actions, _|
        Array(actions).select { Sourced::Actions::Append === it }.flat_map(&:messages)
      end
      history + appended
    end
  end

  # What +reactor+ appends reacting to +trigger+ (already in the store),
  # handed what the router would hand it: the trigger as stored, and the
  # partition's history as it is now, later events included.
  def reacted(reactor, trigger, **keys)
    store = Sidereal.config['sourced.store']
    claimed = store.read(Sourced::Selector[trigger.class].by(**keys)).messages.find { it.id == trigger.id }
    raise ArgumentError, "#{trigger.class} #{trigger.id} isn't in the store" unless claimed

    history = store.read(reactor.history_selector.bind(**keys)).excluding([claimed])
    reactor.handle_batch(keys, [claimed], history:, replaying: false).flat_map do |actions, _|
      Array(actions).select { Sourced::Actions::Append === it }.flat_map(&:messages)
    end
  end
end

